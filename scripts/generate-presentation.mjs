import assert from 'node:assert/strict';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const load = (path) => readFileSync(resolve(root, path), 'utf8');
const quote = JSON.stringify;
const symbol = (id) => id.replace(/[._]([a-z])/g, (_, c) => c.toUpperCase());
export const catalogPath = 'shared/presentation/catalog.v1.json';
const slots = (text) =>
  [...text.matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort();
export function validateCatalog(catalog) {
  assert.equal(catalog.version, 1);
  assert.equal(catalog.sourceLocale, 'en');
  const members = new Set();
  const categoryIDs = new Set();
  for (const category of catalog.categories) {
    assert(!categoryIDs.has(category.id), `Duplicate category ${category.id}`);
    categoryIDs.add(category.id);
    assert.match(category.color, /^#[0-9a-fA-F]{6}$/);
    assert(
      catalog.messages[category.message],
      `Missing message ${category.message}`,
    );
    for (const sport of category.sports) {
      assert(!members.has(sport), `Duplicate sport membership: ${sport}`);
      members.add(sport);
    }
    assert(category.sports.length > 0);
  }
  for (const [id, message] of Object.entries(catalog.messages)) {
    assert(message.context.trim(), `Missing context: ${id}`);
    assert(message.source.trim(), `Missing source: ${id}`);
    assert.deepEqual(
      slots(message.source),
      Object.keys(message.arguments).sort(),
      `Placeholder mismatch: ${id}`,
    );
    assert(
      Object.values(message.arguments).every((type) =>
        ['string', 'number'].includes(type),
      ),
      `Invalid argument: ${id}`,
    );
    if (message.plural) {
      assert.equal(
        message.arguments[message.plural.argument],
        'number',
        `Invalid plural argument: ${id}`,
      );
      for (const form of ['one', 'other']) {
        assert.equal(
          typeof message.plural[form],
          'string',
          `Missing plural ${form}: ${id}`,
        );
        assert.deepEqual(
          slots(message.plural[form]),
          Object.keys(message.arguments).sort(),
          `Plural placeholder mismatch: ${id}`,
        );
      }
    }
  }
  for (const [id, item] of Object.entries({
    ...catalog.actions,
    ...catalog.metrics,
  })) {
    for (const ref of [item.message, item.iosMessage].filter(Boolean))
      assert(catalog.messages[ref], `Unknown message ${ref}: ${id}`);
    assert(
      item.webGlyph && item.iosGlyph && item.colorToken,
      `Missing platform mapping: ${id}`,
    );
  }
  for (const action of Object.values(catalog.actions)) {
    assert.equal(typeof action.mirrorsInRTL, 'boolean');
    for (const [variant, glyph] of Object.entries(
      action.iosGlyphVariants ?? {},
    )) {
      assert.match(variant, /^[a-z][a-zA-Z]*$/);
      assert.equal(typeof glyph, 'string');
      assert(glyph.trim(), 'Empty native action glyph variant');
    }
  }
  return members;
}

export function generatedFiles(catalog, existingCatalog) {
  const members = validateCatalog(catalog);
  const sportSource = load(
    'ios/ActivityMap/ActivityMap/Models/SportType.swift',
  );
  const nativeSports = [...sportSource.matchAll(/case \w+ = "([^"]+)"/g)].map(
    (m) => m[1],
  );
  assert.deepEqual(
    [...members].sort(),
    nativeSports.sort(),
    'Native protocol sport coverage differs',
  );
  const metricRows = load(
    'ios/ActivityMap/ActivityMap/Support/ActivityMetricRow.swift',
  );
  const nativeMetricIDs = [
    'date',
    ...[...metricRows.matchAll(/add\("([^"]+)"/g)].map((match) => match[1]),
  ];
  assert.deepEqual(
    nativeMetricIDs.sort(),
    Object.values(catalog.metrics)
      .map((metric) => metric.iosRowID)
      .sort(),
    'Native standalone metric coverage differs',
  );
  const protocolSource = load('src/server/strava/types.ts');
  for (const sport of members)
    assert(
      protocolSource.includes(`'${sport}'`),
      `Unknown protocol sport: ${sport}`,
    );
  const generated = new Map();
  const args = Object.entries(catalog.messages)
    .map(([id, message]) => {
      const fields = Object.entries(message.arguments)
        .map(([name, type]) => `${name}: ${type}`)
        .join('; ');
      return `  ${quote(id)}: ${fields ? `{ ${fields} }` : 'Record<never, never>'};`;
    })
    .join('\n');
  generated.set(
    'src/lib/presentation/catalog.generated.ts',
    `// Generated by scripts/generate-presentation.mjs. Do not edit.\nexport const presentation = ${JSON.stringify(catalog, null, 2)} as const;\nexport type MessageID = keyof typeof presentation.messages;\nexport type ActionID = keyof typeof presentation.actions;\nexport type MetricID = keyof typeof presentation.metrics;\nexport type CategoryID = typeof presentation.categories[number]['id'];\nexport type SportID = typeof presentation.categories[number]['sports'][number];\nexport type MessageArguments = {\n${args}\n};\n`,
  );
  const swiftMessages = Object.entries(catalog.messages)
    .map(([id, message]) => {
      const params = Object.entries(message.arguments).map(
        ([name, type]) => `_ ${name}: ${type === 'number' ? 'Int' : 'String'}`,
      );
      const value = message.source.replace(/\{(\w+)\}/g, '\\($1)');
      // Literal keys and interpolation retain extractable native localization metadata.
      const line = `LocalizedStringResource(${quote(id)}, defaultValue: ${quote(value).replaceAll('\\\\(', '\\(')}, table: "Presentation", locale: locale, comment: ${quote(message.context)})`;
      return `    static func ${symbol(id)}(${[...params, 'locale: Locale = .current'].join(', ')}) -> LocalizedStringResource {\n        ${line}\n    }`;
    })
    .join('\n');
  const categories = catalog.categories
    .map(
      (c) =>
        `        case ${quote(c.id)}: AppMessages.${symbol(c.message)}(locale: locale)`,
    )
    .join('\n');
  const sports = catalog.categories
    .flatMap((c) => c.sports.map((s) => `        ${quote(s)}: ${quote(c.id)},`))
    .join('\n');
  const metrics = Object.entries(catalog.metrics)
    .map(
      ([, m]) =>
        `        case ${quote(m.iosRowID)}: (AppMessages.${symbol(m.message)}(locale: locale), ${quote(m.iosGlyph)})`,
    )
    .join('\n');
  const actions = Object.entries(catalog.actions)
    .map(
      ([id, a]) =>
        `        case ${quote(id)}: (AppMessages.${symbol(a.iosMessage ?? a.message)}(locale: locale), ${quote(a.iosGlyph)}, ${a.mirrorsInRTL})`,
    )
    .join('\n');
  const actionVariants = Object.entries(catalog.actions)
    .flatMap(([id, action]) =>
      Object.entries(action.iosGlyphVariants ?? {}).map(
        ([variant, glyph]) =>
          `        case (${quote(id)}, ${quote(variant)}): ${quote(glyph)}`,
      ),
    )
    .join('\n');
  generated.set(
    'ios/ActivityMap/ActivityMap/Support/Presentation.generated.swift',
    `// Generated by scripts/generate-presentation.mjs. Do not edit.\nimport Foundation\n\nnonisolated enum AppMessages {\n${swiftMessages}\n}\n\nnonisolated enum SportPresentation {\n    static let categoryIDs: [String: String] = [\n${sports}\n    ]\n    static func name(_ id: String, locale: Locale = .current) -> LocalizedStringResource {\n        switch id {\n${categories}\n        default: AppMessages.categoryMisc(locale: locale)\n        }\n    }\n}\n\nnonisolated enum MetricPresentation {\n    static func definition(_ rowID: String, locale: Locale = .current) -> (title: LocalizedStringResource, glyph: String)? {\n        switch rowID {\n${metrics}\n        default: nil\n        }\n    }\n}\n\nnonisolated enum NativeActionID: String, CaseIterable {\n${Object.keys(
      catalog.actions,
    )
      .map((id) => `    case ${id}`)
      .join(
        '\n',
      )}\n}\n\nnonisolated enum ActionPresentation {\n    static func glyph(_ id: NativeActionID, variant: String? = nil) -> String {\n        switch (id.rawValue, variant) {\n${actionVariants}\n        default: definition(id.rawValue)!.glyph\n        }\n    }\n    static func definition(_ id: String, locale: Locale = .current) -> (title: LocalizedStringResource, glyph: String, mirrorsInRTL: Bool)? {\n        switch id {\n${actions}\n        default: nil\n        }\n    }\n}\n`,
  );
  let existing = existingCatalog ?? { strings: {} };
  if (!existingCatalog) {
    try {
      existing = JSON.parse(
        load('ios/ActivityMap/ActivityMap/Resources/Presentation.xcstrings'),
      );
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
  }
  const strings = {};
  for (const [id, message] of Object.entries(catalog.messages)) {
    const native = (text) =>
      text.replace(/\{(\w+)\}/g, (_, name) =>
        message.arguments[name] === 'number' ? '%lld' : '%@',
      );
    const en = message.plural
      ? {
          variations: {
            plural: Object.fromEntries(
              ['one', 'other'].map((form) => [
                form,
                {
                  stringUnit: {
                    state: 'translated',
                    value: native(message.plural[form]),
                  },
                },
              ]),
            ),
          },
        }
      : { stringUnit: { state: 'translated', value: native(message.source) } };
    // Own source semantics; retain translator-maintained target localizations.
    for (const [locale, value] of Object.entries(
      existing.strings[id]?.localizations ?? {},
    )) {
      if (locale === 'en') continue;
      const expected = Object.values(message.arguments)
        .map((type) => (type === 'number' ? 'lld' : '@'))
        .sort();
      // Check each plural form separately; a translator may add zero/few/many.
      const forms = value.variations?.plural
        ? Object.values(value.variations.plural)
        : [value];
      for (const form of forms) {
        const placeholders = [
          ...JSON.stringify(form).matchAll(/%(?:\d+\$)?(lld|@)/g),
        ]
          .map((m) => m[1])
          .sort();
        assert.deepEqual(
          placeholders,
          expected,
          `Translation placeholder mismatch: ${locale}/${id}`,
        );
      }
      assert(
        !message.plural || value.variations?.plural?.other,
        `Translation missing plural other: ${locale}/${id}`,
      );
    }
    strings[id] = {
      comment: message.context,
      extractionState: 'manual',
      localizations: { ...existing.strings[id]?.localizations, en },
    };
  }
  generated.set(
    'ios/ActivityMap/ActivityMap/Resources/Presentation.xcstrings',
    JSON.stringify({ sourceLanguage: 'en', strings, version: '1.0' }, null, 2) +
      '\n',
  );
  for (const category of catalog.categories) {
    const assets = `ios/ActivityMap/ActivityMap/Assets.xcassets/${category.artwork}`;
    generated.set(
      `${assets}.imageset/sport.svg`,
      load(`shared/presentation/artwork/${category.id}.svg`),
    );
    generated.set(
      `${assets}.imageset/Contents.json`,
      JSON.stringify(
        {
          images: [{ filename: 'sport.svg', idiom: 'universal' }],
          info: { author: 'xcode', version: 1 },
          properties: {
            'preserves-vector-representation': true,
            'template-rendering-intent': 'template',
          },
        },
        null,
        2,
      ) + '\n',
    );
    const [red, green, blue] = [1, 3, 5].map(
      (offset) => `0x${category.color.slice(offset, offset + 2)}`,
    );
    generated.set(
      `${assets}.colorset/Contents.json`,
      JSON.stringify(
        {
          colors: [
            {
              idiom: 'universal',
              color: {
                'color-space': 'srgb',
                components: { red, green, blue, alpha: '1.000' },
              },
            },
          ],
          info: { author: 'xcode', version: 1 },
        },
        null,
        2,
      ) + '\n',
    );
  }
  return generated;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = generatedFiles(JSON.parse(load(catalogPath)));
  for (const [path, text] of files) {
    if (process.argv.includes('--check')) {
      let actual;
      try {
        actual = load(path);
      } catch {
        /* report missing generated file below */
      }
      assert.equal(
        actual,
        text,
        `Generated drift: ${path}; run node scripts/generate-presentation.mjs`,
      );
    } else {
      mkdirSync(dirname(resolve(root, path)), { recursive: true });
      writeFileSync(resolve(root, path), text);
    }
  }
  console.log(
    `Presentation ${process.argv.includes('--check') ? 'validated' : 'generated'} (${files.size} resources).`,
  );
}
