import { readFileSync, writeFileSync } from 'node:fs';

const source = new URL('../shared/places/symbols.json', import.meta.url);
const target = new URL(
  '../ios/ActivityMap/ActivityMap/Places/PlaceGlyph.generated.swift',
  import.meta.url,
);
const symbols = JSON.parse(readFileSync(source, 'utf8'));
const point = (x, y) => `point(${x}, ${y})`;
const cases = Object.entries(symbols)
  .map(([kind, symbol]) => {
    const commands = symbol.commands.map(([op, ...args]) => {
      switch (op) {
        case 'M':
          return `path.move(to: ${point(...args)})`;
        case 'L':
          return `path.addLine(to: ${point(...args)})`;
        case 'Q':
          return `path.addQuadCurve(to: ${point(...args.slice(2))}, control: ${point(...args.slice(0, 2))})`;
        case 'Z':
          return 'path.closeSubpath()';
        default:
          throw new Error(`Unknown place path command: ${op}`);
      }
    });
    commands.push(
      symbol.strokeWidth
        ? `return path.strokedPath(StrokeStyle(lineWidth: ${symbol.strokeWidth} * scale, lineCap: .round, lineJoin: .round))`
        : 'return path',
    );
    return `        case .${kind}:\n${commands.map((command) => '            ' + command).join('\n')}`;
  })
  .join('\n');
const chartCases = Object.entries(symbols)
  .map(([kind, symbol]) => {
    const size = symbol.chartSize;
    return `        case .${kind}: return (size: ${size}, diameter: ${symbol.chartDiameter}, offset: ${4 + symbol.chartDiameter / 2})`;
  })
  .join('\n');
const output = `// Generated by scripts/generate-place-symbols.mjs from shared/places/symbols.json.
import SwiftUI

nonisolated struct PlaceGlyph: Shape {
    let kind: ActivityMapAPI.PlaceKind
    static func chartSymbol(for kind: ActivityMapAPI.PlaceKind) -> (size: CGFloat, diameter: CGFloat, offset: CGFloat) {
        switch kind {
${chartCases}
        }
    }
    func path(in rect: CGRect) -> Path {
        let scale = min(rect.width, rect.height) / 24
        let origin = CGPoint(x: rect.midX - 12 * scale, y: rect.midY - 12 * scale)
        func point(_ x: CGFloat, _ y: CGFloat) -> CGPoint {
            CGPoint(x: origin.x + x * scale, y: origin.y + y * scale)
        }
        var path = Path()
        switch kind {
${cases}
        }
    }
}
`;
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output)
    throw new Error('Run node scripts/generate-place-symbols.mjs');
} else writeFileSync(target, output);
